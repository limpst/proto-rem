def signals_for(segment_id: str | None, reason: str = "") -> dict:
    """리서치 실패 시 쓸 대체 신호.

    kind='sector' 로 표시해 두면 화면이 "확인된 사실" 이 아니라
    "업종 일반 특성" 으로 구분해 보여준다.
    """
    facts = facts_for(segment_id)
    return {
        "facts": facts,
        "building_signals": {"types": [], "scale": "unknown", "age_hint": "unknown"},
        "confidence": "low",
        "kind": "sector",
        "note": ("홈페이지에서 사실을 확보하지 못해 업종 일반 특성으로 대체했습니다. "
                 "이 문안은 그 회사에서 확인한 내용이 아니므로 검토에서 반드시 확인하세요."
                 + (f" (사유: {reason})" if reason else "")),
    }


def is_sector(signals: dict | None) -> bool:
    return bool(signals) and signals.get("kind") == "sector"


