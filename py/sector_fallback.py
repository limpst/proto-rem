# 문안 기본값 — AI 가 문장을 못 만들었을 때 쓰는 예비 문안.
#
# 사람이 검토 단계에서 반드시 손보도록 만든 뼈대다. 그래서
#   - 회사 고유 사실을 넣지 않는다 (확인 없이 아는 척하면 안 된다)
#   - 확인 제안형으로만 쓴다 ("해당하는 경우가 많습니다")
#   - 실적은 세그먼트에 등록된 실제 실적에서만 인용한다
# ─────────────────────────────────────────────────────────────────────
def template_for(segment, persona, company, channel: str = "email") -> dict:
    """AI 없이 조립하는 예비 문안. 병합필드 {{name}} {{title}} {{company}} 를 쓴다."""
    refs = (segment or {}).get("refs") or []
    ref_line = ("\n".join(f"· {r}" for r in refs[:3])) if refs else ""
    pain = (segment or {}).get("pain") or ""
    trigger = (segment or {}).get("trigger") or ""
    offer = (segment or {}).get("offer") or "관련 자료를 무상으로 정리해 드립니다."
    label = (segment or {}).get("label") or "고객"

    subject = f"{label} 시설 점검 주기, 한 번 확인해 보시겠습니까"

    body = f"""{{{{company}}}} {{{{title}}}} {{{{name}}}}님께

{company['name']} {persona['signer']}입니다. {company['tagline']}으로
업력 {company['years']}년, 누적 진단 {company['projects']}건을 수행해 왔습니다.

{pain}
이런 시설은 {trigger}에 해당하는 경우가 많아, 현재 점검 이력 기준으로
다음 도래 시점을 한 번 확인해 보시길 권해 드립니다.

{('저희가 수행한 유사 사례입니다.' + chr(10) + ref_line) if ref_line else ''}

{offer}
회신만 주시면 준비해 드리겠습니다."""

    return {
        "subject": subject,
        "body": body,
        "evidence_used": [trigger] if trigger else [],
        "refs_used": refs[:3],
        "cta": offer,
        "kind": "sector",
        "note": "AI 생성에 실패해 업종 기본 문안으로 대체했습니다. "
                "회사 고유 내용이 없으니 검토에서 반드시 다듬어 주세요.",
    }
