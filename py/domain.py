def segment(sid: str | None) -> dict | None:
    for s in SEGMENTS:
        if s["id"] == sid:
            return s
    return None


_CO_NOISE = re.compile(r"㈜|\(주\)|주식회사|\(유\)|유한회사|\s+")


def norm_co(s: str | None) -> str:
    """회사명 비교용 정규화: ㈜, (주), 주식회사, 공백을 지운다."""
    return _CO_NOISE.sub("", str(s or "")).lower()


_OWN_CO = norm_co(COMPANY["name"])


def classify(card: dict) -> dict:
    # 사람이 직접 제외한 명함 (본인 프로필 등 명함첩에 없는 항목이 API 응답에 섞여 온다)
    if card.get("excluded"):
        return {"segmentId": "excluded", "score": 0}

    # 자사 명함(에이톰 임직원)은 발송 대상이 아니다. 명함첩에는 당연히 섞여 있다.
    if norm_co(card.get("company")) == _OWN_CO:
        return {"segmentId": "internal", "score": 0}

    hay = " ".join(str(card.get(k) or "") for k in ("company", "dept", "title", "note"))
    best, best_score = None, 0
    for seg in SEGMENTS:
        score = sum(1 for k in seg["keywords"] if k in hay)
        if score > best_score:
            best, best_score = seg, score
    return {"segmentId": best["id"] if best else "unclassified", "score": best_score}
